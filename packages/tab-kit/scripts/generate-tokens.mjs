#!/usr/bin/env node
// Generates tokens.css — the default `--cadencr-*` values — from the desktop
// app's CadencR Dark / CadencR Light theme blocks, restricted to the theme
// token vocabulary in packages/desktop/src/lib/themes/tokens.ts.
//
//   node scripts/generate-tokens.mjs          write tokens.css
//   node scripts/generate-tokens.mjs --check  exit 1 when tokens.css is stale
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const desktopSrc = join(root, "../desktop/src");
export const TOKENS_CSS = join(root, "tokens.css");

/** Token names declared by a `export const NAME = [ ... ] as const` array. */
function readKeyArray(source, constName) {
  const match = source.match(new RegExp(`export const ${constName} = \\[([\\s\\S]*?)\\] as const`));
  if (!match) throw new Error(`${constName} not found in tokens.ts`);
  return [...match[1].matchAll(/"(--[a-z0-9-]+)"/g)].map((m) => m[1]);
}

export function readTokenKeys() {
  const source = readFileSync(join(desktopSrc, "lib/themes/tokens.ts"), "utf8");
  return {
    required: readKeyArray(source, "THEME_TOKEN_KEYS"),
    optional: readKeyArray(source, "THEME_OPTIONAL_TOKEN_KEYS"),
  };
}

/** Every declaration of the blocks that style exactly `themeId` at the root. */
function readThemeDeclarations(css, themeId) {
  const own = `:root[data-theme="${themeId}"]`;
  const allowed = new Set([":root", ":root:not([data-theme])", own]);
  const declarations = new Map();
  for (const [, selectorList, body] of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    const selectors = selectorList.split(",").map((s) => s.trim());
    if (!selectors.includes(own) || !selectors.every((s) => allowed.has(s))) continue;
    for (const declaration of body.split(";")) {
      const at = declaration.indexOf(":");
      if (at === -1) continue;
      const name = declaration.slice(0, at).trim();
      if (name.startsWith("--")) {
        declarations.set(
          name,
          declaration
            .slice(at + 1)
            .replace(/\s+/g, " ")
            .trim(),
        );
      }
    }
  }
  return declarations;
}

function themeBlock(selector, scheme, declarations, keys) {
  const lines = [`${selector} {`, `  color-scheme: ${scheme};`];
  for (const key of keys) {
    const value = declarations.get(key);
    if (value === undefined) continue;
    const rewritten = value.replace(/var\(--([a-z0-9-]+)/g, (all, name) => {
      if (!keys.includes(`--${name}`)) throw new Error(`${key} references --${name}`);
      return `var(--cadencr-${name}`;
    });
    lines.push(`  --cadencr-${key.slice(2)}: ${rewritten};`);
  }
  lines.push("}");
  return lines.join("\n");
}

export function renderTokensCss() {
  const { required, optional } = readTokenKeys();
  const keys = ["--radius", ...required, ...optional];
  const css = readFileSync(join(desktopSrc, "theme-cadencr.css"), "utf8").replace(
    /\/\*[\s\S]*?\*\//g,
    "",
  );
  const dark = readThemeDeclarations(css, "cadencr-dark");
  const light = readThemeDeclarations(css, "cadencr-light");
  for (const [name, declarations] of [
    ["cadencr-dark", dark],
    ["cadencr-light", light],
  ]) {
    const missing = required.filter((key) => !declarations.has(key));
    if (missing.length) throw new Error(`${name} does not declare ${missing.join(", ")}`);
  }
  return [
    "/*",
    " * @cadencr/tab-kit — default theme tokens (CadencR Dark, CadencR Light).",
    " * GENERATED by scripts/generate-tokens.mjs from packages/desktop/src/theme-cadencr.css;",
    " * do not edit by hand. Inside Cadencr the SDK overrides these with the live theme.",
    " */",
    "",
    themeBlock(':root,\n:root[data-appearance="dark"]', "dark", dark, keys),
    "",
    themeBlock(':root[data-appearance="light"]', "light", light, keys),
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = renderTokensCss();
  if (process.argv.includes("--check")) {
    if (readFileSync(TOKENS_CSS, "utf8") !== next) {
      console.error("tokens.css is stale: run `pnpm --filter @cadencr/tab-kit generate:tokens`");
      process.exit(1);
    }
  } else {
    writeFileSync(TOKENS_CSS, next);
  }
}
