#!/usr/bin/env node
// Writes a dev-mode bearer token to two `.env` files (same value, different
// keys/loaders):
//   - `<repo>/.env`                 → CADENCE_AUTH_TOKEN (Rust crates, dotenvy)
//   - `<repo>/packages/tauri/.env`  → VITE_API_TOKEN     (Vite, envFallback)
// Idempotent — run on every `pnpm dev`. Production mints a fresh token per
// launch in the Tauri shell instead.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { randomBytes } from "node:crypto";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const ROOT_ENV = join(REPO_ROOT, ".env");
const VITE_ENV = join(REPO_ROOT, "packages/tauri/.env");

const ROOT_KEY = "CADENCE_AUTH_TOKEN";
const VITE_KEY = "VITE_API_TOKEN";

function generateToken() {
  return randomBytes(32).toString("base64url");
}

function parseEnv(contents) {
  const map = new Map();
  for (const line of contents.split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    map.set(trimmed.slice(0, eq).trim(), trimmed.slice(eq + 1).trim());
  }
  return map;
}

/** Appends `key=value` if absent; never overwrites. Returns whether it wrote. */
function ensureKey(path, key, value, header) {
  const existing = existsSync(path) ? readFileSync(path, "utf8") : "";
  const parsed = parseEnv(existing);
  if (parsed.has(key)) {
    return false;
  }
  const trailing = existing.length === 0 || existing.endsWith("\n") ? "" : "\n";
  const headerBlock = existing.length === 0 && header ? header : "";
  writeFileSync(path, existing + trailing + headerBlock + `${key}=${value}\n`, {
    mode: 0o600,
  });
  return true;
}

const rootParsed = parseEnv(existsSync(ROOT_ENV) ? readFileSync(ROOT_ENV, "utf8") : "");
const viteParsed = parseEnv(existsSync(VITE_ENV) ? readFileSync(VITE_ENV, "utf8") : "");

// Reuse any existing value so the two files never drift apart.
const token =
  rootParsed.get(ROOT_KEY) ?? viteParsed.get(VITE_KEY) ?? generateToken();

const header =
  "# Dev-mode auth token. Auto-generated by scripts/ensure-dev-token.mjs.\n" +
  "# Delete this file to rotate the token.\n";

const wroteRoot = ensureKey(ROOT_ENV, ROOT_KEY, token, header);
const wroteVite = ensureKey(VITE_ENV, VITE_KEY, token, header);

if (wroteRoot) console.log(`[ensure-dev-token] wrote ${ROOT_KEY} to ${ROOT_ENV}`);
if (wroteVite) console.log(`[ensure-dev-token] wrote ${VITE_KEY} to ${VITE_ENV}`);
if (!wroteRoot && !wroteVite) {
  console.log(`[ensure-dev-token] ${ROOT_KEY} and ${VITE_KEY} already set`);
}
